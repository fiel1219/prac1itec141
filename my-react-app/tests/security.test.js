import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'

test('database isolation blocks cross-laboratory access and approvals are atomic and admin-only',async()=>{
  const db=new PGlite()
  const ids={system:'11111111-1111-4111-8111-111111111111',operator:'22222222-2222-4222-8222-222222222222',other:'33333333-3333-4333-8333-333333333333'}
  try{
    await db.exec(`create role anon;create role authenticated;create schema auth;
      create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
      create function auth.jwt() returns jsonb language sql as $$select jsonb_build_object('email',current_setting('test.email',true))$$;
      grant usage on schema public,auth to anon,authenticated;`)
    const file=name=>readFile(new URL(`../supabase/${name}`,import.meta.url),'utf8')
    await db.exec((await file('schema.sql')).replace('create extension if not exists pgcrypto;',''))
    for(const name of ['user_accounts.sql','inventoscan_features.sql','inventory_qr.sql','inventory_unit_actions.sql','inventory_return_repair.sql','inventory_permanent_delete.sql','inventory_shelf_items.sql','inventory_item_descriptions.sql','inventory_item_categories.sql','inventory_consumable_quantities.sql','inventory_consumable_actions.sql','inventory_bulk_actions.sql','inventory_laboratories.sql','user_laboratories.sql','inventory_checks.sql'])await db.exec(await file(name))
    for(const [name,id] of Object.entries(ids))await db.query(`insert into user_accounts(id,full_name,email,role) values($1,$2,$3,$4)`,[id,name,`${name}@example.test`,name==='system'?'Admin':'Operator'])
    const login=async name=>{await db.exec('reset role;set role authenticated');await db.query(`select set_config('test.uid',$1,false),set_config('test.email',$2,false)`,[ids[name],`${name}@example.test`])}
    const query=(sql,args=[])=>db.query(sql,args)
    const scalar=async(sql,args=[])=>(await query(sql,args)).rows[0].id
    const science=await scalar('select id from laboratories limit 1')
    await login('system')
    const chemistry=await scalar(`select inventory_save_laboratory(null,'Chemistry','') as id`)
    for(const name of ['operator','other'])await query('select inventory_save_user_assignments($1,$2,$3::jsonb)',[ids[name],'Operator',JSON.stringify([{laboratory_id:name==='operator'?science:chemistry,role:'Laboratory Operator'}])])
    const createShelf=(lab,code)=>scalar(`select inventory_save_laboratory_shelf($1,null,$2,$2,'') as id`,[lab,code])
    const shelf=await createShelf(science,'A-01'),foreignShelf=await createShelf(chemistry,'A-01')
    await query(`select inventory_receive_categorized_items($1,'Monitor','equipment',1,'')`,[foreignShelf])
    const foreignUnit=await scalar('select id from inventory_units where shelf_id=$1',[foreignShelf])
    await db.exec('reset role');const hardening=await file('security_hardening.sql');await db.exec(hardening);await db.exec(hardening)
    const accessUpgrade=await file('system_admin_laboratory_access.sql');await db.exec(accessUpgrade);await db.exec(accessUpgrade)
    await login('operator')
    assert.equal((await query('select * from laboratories')).rows.length,1)
    assert.equal((await query('select * from shelves')).rows.length,1)
    assert.equal((await query('select * from inventory_units')).rows.length,0)
    assert.equal((await query('select * from user_accounts')).rows.length,1)
    assert.equal((await query('select * from account_approvals')).rows.length,0)
    await assert.rejects(query(`update laboratories set name='Hacked' where id=$1`,[science]),/Only a System Admin/)
    await assert.rejects(query(`select inventory_save_laboratory(null,'Hacked','')`),/Only a System Admin/)
    await login('system')
    await query(`select inventory_save_user_assignments($1,'Operator',$2::jsonb)`,[ids.operator,JSON.stringify([{laboratory_id:science,role:'Laboratory Admin'}])])
    await login('operator')
    assert.equal((await query('select * from shelves')).rows.length,1)
    assert.equal((await query('select * from inventory_units where id=$1',[foreignUnit])).rows.length,0)
    await assert.rejects(query(`select inventory_update_unit($1,'available','good','Lab admin cannot access another lab')`,[foreignUnit]),/shelf|permission/i)
    await assert.rejects(query(`select inventory_save_laboratory(null,'Hacked','')`),/Only a System Admin/)
    const destination=await createShelf(science,'A-02')
    await query(`select inventory_receive_categorized_items($1,'Microscope','equipment',2,'')`,[shelf])
    await query(`select inventory_receive_categorized_items($1,'Gloves','consumable',5,'')`,[shelf])
    const unit=await scalar(`select id from inventory_units where shelf_id=$1 and inventory_kind='equipment' order by unit_number limit 1`,[shelf])
    const borrower=await scalar(`insert into borrowers(name,identity_number) values('Student','S-001') returning id`)
    await query('select inventory_checkout($1,$2,current_date+1)',[unit,borrower])
    const loan=await scalar('select id from transactions where unit_id=$1',[unit])
    assert.ok((await query('select * from stock_movements')).rows.every(row=>row.laboratory_id===science))
    await query(`select inventory_return($1,'good')`,[loan])
    await assert.rejects(query(`select inventory_move_unit($1,$2,'')`,[unit,foreignShelf]),/active|shelf|permission/i)
    await query(`select inventory_move_unit($1,$2,'')`,[unit,destination])
    await assert.rejects(query(`select inventory_update_unit($1,'available','good','')`,[foreignUnit]),/shelf|permission/i)
    await assert.rejects(query(`insert into inventory_units(shelf_id,unit_number,item_name,inventory_kind) values($1,10,'Injected','equipment')`,[foreignShelf]),/row-level security/)
    assert.equal((await query(`update inventory_units set condition='damaged' where id=$1 returning id`,[foreignUnit])).rows.length,0)
    await login('other')
    assert.equal((await query('select * from transactions')).rows.length,0)
    assert.equal((await query('select * from stock_movements')).rows.length,1)
    await assert.rejects(query(`select inventory_return($1,'good')`,[loan]),/not found|returned/)
    await login('system')
    assert.equal((await query('select * from laboratories')).rows.length,2)
    assert.equal((await query('select * from shelves')).rows.length,3)
    assert.equal((await query('select * from inventory_units')).rows.length,4)
    assert.equal((await query('select * from transactions')).rows.length,1)
    assert.equal((await query('select * from laboratory_memberships where user_id=$1',[ids.system])).rows.length,0)
    await query(`select inventory_update_unit($1,'under_maintenance','damaged','Admin inspection')`,[foreignUnit])
    const adminCheck=await scalar(`select inventory_save_shelf_check($1,$2,$3::jsonb,'System Admin inspection') as id`,[chemistry,foreignShelf,JSON.stringify([{unit_id:foreignUnit,expected_status:'under_maintenance',expected_condition:'damaged',expected_quantity:1,condition:'good'}])])
    assert.equal((await query('select performed_by_user_id from inventory_checks where id=$1',[adminCheck])).rows[0].performed_by_user_id,ids.system)
    await query(`select inventory_receive_categorized_items($1,'Wipes','consumable',3,'')`,[foreignShelf])
    await query(`select inventory_item_category_stock_move($1,'out','Wipes','consumable',1,'Class supplies')`,[foreignShelf])
    assert.equal((await query(`select quantity from inventory_units where shelf_id=$1 and item_name='Wipes'`,[foreignShelf])).rows[0].quantity,2)
    await query('select inventory_checkout($1,$2,current_date+1)',[foreignUnit,borrower])
    const adminLoan=await scalar('select id from transactions where unit_id=$1',[foreignUnit])
    await query(`select inventory_return($1,'good')`,[adminLoan])
    assert.ok((await query('select * from stock_movements')).rows.some(row=>row.laboratory_id===chemistry))
    await query(`select inventory_move_unit($1,$2,'System transfer')`,[foreignUnit,destination])
    assert.equal((await query('select shelf_id from inventory_units where id=$1',[foreignUnit])).rows[0].shelf_id,destination)
    await assert.rejects(query('select inventory_delete_laboratory($1)',[science]),/shelves before/)
    const empty=await scalar(`select inventory_save_laboratory(null,'Empty lab','') as id`)
    await query('select inventory_delete_laboratory($1)',[empty])
    await db.exec('reset role')
    const request=await scalar(`insert into account_approvals(full_name,email) values('New User','NEW@example.test') returning id`)
    await login('operator')
    await assert.rejects(query(`select inventory_approve_account($1,'Admin')`,[request]),/Only a System Admin/)
    await assert.rejects(query(`update account_approvals set status='approved' where id=$1`,[request]),/permission denied/)
    await login('system')
    await query(`select inventory_approve_account($1,'Operator')`,[request])
    assert.equal((await query(`select * from user_accounts where email='new@example.test'`)).rows[0].role,'Operator')
    assert.equal((await query('select * from account_approvals where id=$1',[request])).rows[0].reviewed_by,'system')
    await assert.rejects(query(`select inventory_approve_account($1,'Admin')`,[request]),/already reviewed/)
    await db.exec(`reset role;create function public.reject_review() returns trigger language plpgsql as $$begin raise exception 'Review write failed';end$$;
      create trigger reject_review before update on account_approvals for each row execute function public.reject_review();`)
    const failing=await scalar(`insert into account_approvals(full_name,email) values('Failed','failed@example.test') returning id`)
    await login('system');await assert.rejects(query(`select inventory_approve_account($1,'Admin')`,[failing]),/Review write failed/)
    assert.equal((await query(`select * from user_accounts where email='failed@example.test'`)).rows.length,0)
    assert.equal((await query('select status from account_approvals where id=$1',[failing])).rows[0].status,'pending')
    await db.exec('reset role');await query('delete from laboratory_memberships where user_id=$1',[ids.operator])
    await login('operator');assert.equal((await query('select * from shelves')).rows.length,0)
    await assert.rejects(query(`select inventory_save_shelf_check($1,$2,'[]'::jsonb,'')`,[chemistry,foreignShelf]),/Only assigned/)
    await db.exec(`reset role;update user_accounts set status='disabled' where email='other@example.test'`)
    await login('other');assert.equal((await query('select * from inventory_units')).rows.length,0)
    await db.exec(`reset role;update user_accounts set role='Operator' where email='system@example.test'`)
    await login('system')
    assert.equal((await query('select * from shelves')).rows.length,0)
    await assert.rejects(query(`select inventory_save_shelf_check($1,$2,'[]'::jsonb,'')`,[science,shelf]),/Only assigned/)
    await db.exec(`reset role;update user_accounts set role='Admin' where email='system@example.test'`)
    await db.exec(`reset role;update user_accounts set status='disabled' where email='system@example.test'`)
    await login('system')
    for(const table of ['shelves','inventory_units','transactions','stock_movements','inventory_checks'])assert.equal((await query(`select * from ${table}`)).rows.length,0)
    await assert.rejects(query(`select inventory_save_shelf_check($1,$2,'[]'::jsonb,'')`,[science,shelf]),/Only assigned/)
    await db.exec('reset role;set role anon')
    for(const table of ['user_accounts','account_approvals','shelves','inventory_units','borrowers','transactions'])await assert.rejects(query(`select * from public.${table}`),/permission denied/)
    await query(`insert into account_approvals(full_name,email) values('Registration','register@example.test')`)
  }finally{await db.close()}
})
